"""
judge_direct_refusal.py  —  Guard model judge + plot

Read responses.json generated by eval_direct_refusal.py, classify with
WildGuard by default or an OpenRouter LLM, and plot the results.

Usage:
    # WildGuard judge + plot (default)
    python judge_direct_refusal.py --input out_responses/direct_refusal_XXX/responses.json

    # WildGuard judge only
    python judge_direct_refusal.py --input responses.json --mode judge

    # OpenRouter judge
    python judge_direct_refusal.py --input responses.json --judge-backend openrouter

    # Plot only, after judging has finished
    python judge_direct_refusal.py --input responses.json --mode plot

    # Directory input; responses.json / responses_judged.json are detected automatically
    python judge_direct_refusal.py --input out_responses/direct_refusal_XXX/

Environment variable:
    OPENROUTER_API_KEY  (required when --judge-backend openrouter is used)
"""

