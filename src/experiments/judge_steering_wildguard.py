def process_single_input(input_path: Path, args) -> None:
    """Process one input file."""
    if not input_path.exists():
        print(f"[warning] file not found: {input_path}")
        return

    if args.output_dir:
        out_dir = Path(args.output_dir).resolve()
    else:
        out_dir = input_path.parent / f"{input_path.stem}-wildguard-judge"
    out_dir.mkdir(parents=True, exist_ok=True)

    checkpoint_path = out_dir / "judged_rows.json"
    aggregate_path  = out_dir / "aggregate_result.json"
    plots_dir       = out_dir / "plots"
    plots_dir.mkdir(exist_ok=True)

    # Judge phase.
    if args.mode in ("judge", "both"):
        if checkpoint_path.exists():
            print(f"Resuming existing checkpoint: {checkpoint_path}")
            with checkpoint_path.open(encoding="utf-8") as f:
                rows = json.load(f)
        else:
            print(f"Loading responses: {input_path}")
            rows = load_steering_rows(input_path)
            print(f"  Loaded {len(rows)} rows")

        if args.judge_backend == "openrouter":
            judge = OpenRouterJudge(
                model=args.openrouter_model,
                api_key=args.openrouter_api_key,
                workers=args.openrouter_workers,
            )
        else:
            judge = WildGuardJudge(args.wildguard_model, args.guard_batch_size)
        rows = judge.judge_all(rows, checkpoint_path=checkpoint_path)

        with checkpoint_path.open("w", encoding="utf-8") as f:
            json.dump(rows, f, ensure_ascii=False, indent=2)
        print(f"\nSaved judged_rows: {checkpoint_path}")

        agg = aggregate(rows)
        with aggregate_path.open("w", encoding="utf-8") as f:
            json.dump(agg, f, ensure_ascii=False, indent=2)
        print(f"Saved aggregate_result: {aggregate_path}")

    # Plot phase.
    if args.mode in ("plot", "both"):
        if not aggregate_path.exists():
            print(
                f"[warning] Missing aggregate_result.json: {aggregate_path}\n"
                "        Run --mode judge first."
            )
            return
        with aggregate_path.open(encoding="utf-8") as f:
            agg = json.load(f)

        print(f"\n=== Plotting ({plots_dir}) ===")
        plot_overview(agg, plots_dir / "judge_overview.png")
        plot_kl_overview(agg, plots_dir / "kl_divergence.png")
        write_summary_csv(agg.get("by_target_layer_alpha", []), plots_dir / "judge_summary.csv")

        print(f"\n{'='*60}")
        print("Summary (target / layer_group / alpha)")
        print(f"{'='*60}")
        for r in agg.get("by_target_layer_alpha", []):
            kl_str = f"  KL={r['kl_from_baseline']:.4f}" if r.get("kl_from_baseline") is not None else ""
            print(
                f"  {r['target']:12s} {r['layer_group_name']:8s} α={r['alpha']:.1f}  "
                f"refusal={r['refusal']['percentage']:5.1f}%  "
                f"accept={r['accept']['percentage']:5.1f}%  "
                f"other={r['other']['percentage']:5.1f}%  (n={r['total']})"
                f"{kl_str}"
            )


def main() -> None:
    args = parse_args()

    if args.compose_model:
        base_dir = Path(__file__).parent / "out_pt"
        compose_paper_figures(
            base_dir,
            model=args.compose_model,
            output_dir=Path(args.compose_output_dir) if args.compose_output_dir else None,
        )
        return
    
    # Resolve input files.
    if args.input:
        input_files = [Path(args.input).resolve()]
    else:
        if args.mode != "plot":
            raise SystemExit(
                "[error] --input is required in judge or both mode.\n"
                "       Use --mode plot if you want to omit --input."
            )
        input_files = find_default_input_files()
        if not input_files:
            raise SystemExit(
                "[error] No steering files found in the default paths.\n"
                f"       paths: out_pt/llama-3.1-8b-instruct/steering/\n"
                f"             out_pt/qwen2.5-7b-instruct/steering/"
            )
        print(f"Found steering files: {len(input_files)}")
    
    # Process each file.
    for idx, input_path in enumerate(input_files, 1):
        print(f"\n{'='*80}")
        print(f"[{idx}/{len(input_files)}] {input_path.name}")
        print(f"{'='*80}")
        try:
            process_single_input(input_path, args)
        except Exception as e:
            print(f"[error] {input_path.name}: {e}")
            continue

    # Compose paper figures for batch plot mode without --input.
    if not args.input and args.mode in ("plot", "both"):
        base_dir = Path(__file__).parent / "out_pt"
        compose_paper_figures(base_dir)


if __name__ == "__main__":
    main()
